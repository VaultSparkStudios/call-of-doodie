#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { findLatestAuditSidecar, getAuditItems, readAuditSidecar } from "./lib/audit-sidecar.mjs";

const ROOT = process.cwd();
const dateArg = process.argv.find((arg) => arg.startsWith("--date="))?.split("=")[1]
  || process.argv[process.argv.indexOf("--date") + 1];
const sidecar = dateArg
  ? { fullPath: path.join(ROOT, "docs", `AUDIT_${dateArg}.json`) }
  : findLatestAuditSidecar(ROOT);

if (!sidecar || !fs.existsSync(sidecar.fullPath)) {
  console.error("No audit sidecar found.");
  process.exit(1);
}

const audit = readAuditSidecar(sidecar.fullPath);
const items = getAuditItems(audit);
const meta = audit.meta || {};
const outPath = sidecar.fullPath.replace(/\.json$/, ".md");

const rows = items.map((item, index) => {
  const effort = item.effortHours != null ? `${item.effortHours}h` : item.effort || "?";
  const why = String(item.why || "").replace(/\s+/g, " ").slice(0, 220);
  const recipe = String(item.recipe || item.ladder?.L2?.recipe || "").replace(/\s+/g, " ").slice(0, 220);
  return `| ${index + 1} | ${item.tier || ""} | ${item.axis || ""} | ${effort} | ${item.impact ?? ""} | ${item.innovation ?? ""} | ${item.priority ?? ""} | ${item.status || "pending"} | **${item.slug}** — ${why} **Recipe:** ${recipe} |`;
}).join("\n");

const skipped = (audit.skipped || []).map((item) => `- ${item.slug} — ${item.reason}`).join("\n") || "- None";
const execution = (audit.executionLog || []).map((item) => `- ${item.slug}: ${item.status}${item.notes ? ` — ${item.notes}` : ""}`).join("\n");

const md = `<!-- generated-by: /audit skill v1.0 -->\n<!-- generated-at: ${meta.generatedAt || new Date().toISOString().slice(0, 10)} -->\n<!-- project: ${meta.project || "call-of-doodie"} · type: ${meta.type || "game"} -->\n\n# Project Audit — Call-Of-Doodie\n\n> One ranked improvement plan covering verified current-state gaps.\n> Run \`/implement\` to execute in optimal order.\n\n## Top-line\n\n- Total items: ${items.length}\n- Combined Priority: ${meta.combinedPriority ?? items.reduce((sum, item) => sum + Number(item.priority || 0), 0).toFixed(1)}\n- Top 3: ${(meta.top3 || items.slice(0, 3).map((item) => item.slug)).join(" · ")}\n\n## Ranked Plan\n\n| # | Tier | Axis | Effort | Impact | Innov. | Priority | Item |\n|---|:-:|---|---|:-:|:-:|:-:|---|\n${rows}\n\n## Innovation reserve\n\n${items.filter((item) => Number(item.innovation || 0) >= 8).map((item) => `- ${item.slug}`).join("\n") || "- None"}\n\n## Skipped\n\n${skipped}\n${execution ? `\n## Execution Log\n\n${execution}\n` : ""}\n---\n*Generated by \`/audit\` v1.0 · ready for \`/implement\`*\n`;

const renderedMd = md
  .replace(
    "| # | Tier | Axis | Effort | Impact | Innov. | Priority | Item |",
    "| # | Tier | Axis | Effort | Impact | Innov. | Priority | Status | Item |",
  )
  .replace(
    "|---|:-:|---|---|:-:|:-:|:-:|---|",
    "|---|:-:|---|---|:-:|:-:|:-:|:-:|---|",
  );

fs.writeFileSync(outPath, renderedMd);
console.log(`Rendered ${path.relative(ROOT, outPath).replace(/\\/g, "/")}`);
